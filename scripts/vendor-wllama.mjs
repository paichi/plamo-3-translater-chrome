// Reproduce the MV3-specific vendor adaptation; no bundler or application build.
// npm pack @wllama/wllama@3.13.0; tar -xzf wllama-wllama-3.13.0.tgz
// node scripts/vendor-wllama.mjs /path/to/package
// The package's LICENCE is copied to vendor/wllama/LICENSE.
import fs from 'node:fs';
import path from 'node:path';

const source = process.argv[2];
if (!source || JSON.parse(fs.readFileSync(path.join(source, 'package.json'))).version !== '3.13.0') {
  throw new Error('Pass an extracted @wllama/wllama 3.13.0 package directory');
}
const out = path.resolve(import.meta.dirname, '../vendor/wllama');
const generated = fs.readFileSync(path.join(source, 'src/workers-code/generated.ts'), 'utf8');
function code(name) {
  const match = generated.match(new RegExp(`export const ${name} = ("(?:[^"\\\\]|\\\\.)*");`));
  if (!match) throw new Error(`Cannot extract ${name}`);
  return JSON.parse(match[1]);
}
let runtime = fs.readFileSync(path.join(source, 'esm/index.js'), 'utf8');
function replaceRegion(start, end, replacement) {
  const from = runtime.indexOf(start);
  const to = runtime.indexOf(end, from + start.length);
  if (from < 0 || to < 0 || runtime.indexOf(start, from + 1) !== -1) throw new Error(`Upstream changed: ${start}`);
  runtime = runtime.slice(0, from) + replacement + runtime.slice(to);
}
replaceRegion('var createWorker = (workerCode) => {', '\nvar cbToAsyncIter =', `var createWorker = (workerCode) => {
  if (workerCode !== OPFS_UTILS_WORKER_CODE) throw new Error("Dynamic workers are disabled in this MV3 adaptation");
  return new Worker(new URL("./opfs-worker.js", import.meta.url));
};
`);
replaceRegion('      let moduleCode = JSPI_STUB + (yield this.getModuleCode());', '      const nativeFiles = [];', `      // MV3: packaged classic worker, no Blob script or eval. Single-thread only.
      if (this.nbThread || this.resources.compat || this.resources.jsPath) {
        throw new Error("MV3 runtime supports only packaged single-thread workers");
      }
      this.worker = new Worker(new URL("./llama-worker.js", import.meta.url));
      this.worker.onmessage = this.onRecvMsg.bind(this);
      this.worker.onerror = (event) => this.abort(event.message || "Worker failed", "");
      const res = yield this.pushTask({
        verb: "module.init",
        args: [{
          pathConfig: { "wllama.wasm": this.resources.wasmPath },
          nbThread: 0, compat: false, noWebGPU: !!this.resources.noWebGPU
        }, this.useAsyncFile],
        callbackId: this.taskId++
      });
`);
let worker = code('LLAMA_CPP_WORKER_CODE');
const init = "    const argMainScriptBlob = args[0];";
if (!worker.includes(init)) throw new Error('Upstream worker changed');
worker = worker.replace(init, `    RUN_OPTIONS = args[0];
    if (RUN_OPTIONS.noWebGPU) {
      try { Object.defineProperty(WorkerNavigator.prototype, 'gpu', { get: () => ({ requestAdapter: async () => null }) }); } catch {}
    }
    const argMainScriptBlob = null;`);
const emscripten = code('WLLAMA_EMSCRIPTEN_CODE').replace('var Module', 'var ___Module');
fs.mkdirSync(path.join(out, 'wasm'), { recursive: true });
fs.writeFileSync(path.join(out, 'index.js'), runtime);
fs.writeFileSync(path.join(out, 'llama-worker.js'), `// @wllama/wllama 3.13.0: static MV3 worker. Generated by scripts/vendor-wllama.mjs.\nlet RUN_OPTIONS;\nfunction wModuleInit() {\n${emscripten}\nreturn Module;\n}\n${worker}`);
fs.writeFileSync(path.join(out, 'opfs-worker.js'), '// @wllama/wllama 3.13.0: static OPFS utility worker.\n' + code('OPFS_UTILS_WORKER_CODE'));
fs.copyFileSync(path.join(source, 'esm/wasm/wllama.wasm'), path.join(out, 'wasm/wllama.wasm'));
fs.copyFileSync(path.join(source, 'LICENCE'), path.join(out, 'LICENSE'));
console.log('Vendored wllama 3.13.0 with static, single-thread MV3 workers.');
